def text(lang, key, **kwargs):
    # type: (str, str, object) -> str
    """Look up one UI string. Missing keys fall back to Portuguese, then the key."""
    bundle = STRINGS.get(lang) or STRINGS["pt"]
    value = bundle.get(key)
    if value is None:
        value = STRINGS["pt"].get(key, key)
    if not kwargs:
        return value
    return value % kwargs

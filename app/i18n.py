from contextvars import ContextVar

_GENERATION_LANG = ContextVar("generation_lang", default="pt")


def set_generation_lang(lang):
    # type: (str) -> object
    """Remember the language for free text the model writes on this job."""
    chosen = "en" if lang == "en" else "pt"
    return _GENERATION_LANG.set(chosen)


def generation_clause():
    # type: () -> str
    """One line appended to prompts that return a justification or a summary."""
